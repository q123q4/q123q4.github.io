// 导航栏功能
function initNavigation() {
    const hamburger = document.querySelector('.hamburger');
    const navMenu = document.querySelector('.nav-menu');
    const navLinks = document.querySelectorAll('.nav-link');

    // 移动端菜单切换
    if (hamburger) {
        hamburger.addEventListener('click', function() {
            hamburger.classList.toggle('active');
            navMenu.classList.toggle('active');
        });
    }

    // 点击链接关闭移动端菜单
    navLinks.forEach(link => {
        link.addEventListener('click', function() {
            hamburger.classList.remove('active');
            navMenu.classList.remove('active');
        });
    });

    // 滚动时高亮当前部分
    window.addEventListener('scroll', highlightActiveSection);
}

// 高亮当前部分
function highlightActiveSection() {
    const sections = document.querySelectorAll('section');
    const navLinks = document.querySelectorAll('.nav-link');
    
    let current = '';
    sections.forEach(section => {
        const sectionTop = section.offsetTop - 100;
        const sectionHeight = section.clientHeight;
        if (window.scrollY >= sectionTop && window.scrollY < sectionTop + sectionHeight) {
            current = section.getAttribute('id');
        }
    });

    navLinks.forEach(link => {
        link.classList.remove('active');
        if (link.getAttribute('href').substring(1) === current) {
            link.classList.add('active');
        }
    });
}

// 选项卡功能
function initTabs() {
    const tabBtns = document.querySelectorAll('.tab-btn');
    const tabPanes = document.querySelectorAll('.tab-pane');
    
    tabBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            const tabId = this.getAttribute('data-tab');
            
            // 移除所有激活状态
            tabBtns.forEach(b => b.classList.remove('active'));
            tabPanes.forEach(p => p.classList.remove('active'));
            
            // 添加当前激活状态
            this.classList.add('active');
            document.getElementById(tabId).classList.add('active');
        });
    });
}

// 关键词动画
function initKeywordsAnimation() {
    const keywords = document.querySelectorAll('.keyword');
    let index = 0;
    
    function animateKeywords() {
        keywords.forEach((keyword, i) => {
            keyword.style.opacity = '0.3';
            keyword.style.transform = 'scale(0.9)';
        });
        
        keywords[index].style.opacity = '1';
        keywords[index].style.transform = 'scale(1.1)';
        
        index = (index + 1) % keywords.length;
    }
    
    // 每2秒切换一次
    setInterval(animateKeywords, 2000);
    
    // 初始动画
    setTimeout(animateKeywords, 500);
}

// 文章模态框功能
function initArticleModal() {
    const modal = document.getElementById('article-modal');
    const closeBtn = document.querySelector('.close-modal');
    const readMoreBtns = document.querySelectorAll('.read-more-btn');
    
    // 打开模态框
    readMoreBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            const articleId = this.getAttribute('data-target');
            openArticleModal(articleId);
        });
    });
    
    // 关闭模态框
    closeBtn.addEventListener('click', closeArticleModal);
    
    // 点击模态框外部关闭
    modal.addEventListener('click', function(e) {
        if (e.target === modal) {
            closeArticleModal();
        }
    });
    
    // ESC键关闭
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape') {
            closeArticleModal();
        }
    });
}

function openArticleModal(articleId) {
    const modal = document.getElementById('article-modal');
    const article = articlesData[articleId];
    
    if (!article) return;
    
    // 填充内容
    document.getElementById('modal-title').textContent = article.title;
    document.getElementById('modal-date').textContent = article.date;
    
    // 填充标签
    const tagsContainer = document.getElementById('modal-tags');
    tagsContainer.innerHTML = '';
    article.tags.forEach(tag => {
        const tagElement = document.createElement('span');
        tagElement.className = 'modal-tag';
        tagElement.textContent = tag;
        tagsContainer.appendChild(tagElement);
    });
    
    // 填充文章内容
    document.getElementById('modal-content').innerHTML = article.content;
    
    // 显示模态框
    modal.style.display = 'block';
    document.body.style.overflow = 'hidden'; // 防止背景滚动
    
    // 滚动到顶部
    modal.scrollTop = 0;
}

function closeArticleModal() {
    const modal = document.getElementById('article-modal');
    modal.style.display = 'none';
    document.body.style.overflow = 'auto'; // 恢复滚动
}

// 表单处理
function initForms() {
    // 留言板表单
    const guestbookForm = document.getElementById('guestbook-form');
    if (guestbookForm) {
        guestbookForm.addEventListener('submit', handleGuestbookSubmit);
    }

    // 联系表单
    const contactForm = document.getElementById('contact-form');
    if (contactForm) {
        contactForm.addEventListener('submit', handleContactSubmit);
    }
}

// 处理留言板提交
function handleGuestbookSubmit(e) {
    e.preventDefault();
    
    const name = document.getElementById('name').value;
    const email = document.getElementById('email').value;
    const message = document.getElementById('message').value;
    
    if (!name || !message) {
        showNotification('请填写姓名和留言内容', 'error');
        return;
    }

    // 创建新的留言项
    const messagesContainer = document.getElementById('messages-container');
    const newMessage = createMessageElement(name, message);
    
    // 插入到最前面
    messagesContainer.insertBefore(newMessage, messagesContainer.firstChild);
    
    // 清空表单
    guestbookForm.reset();
    
    showNotification('留言提交成功！', 'success');
}

// 创建留言元素
function createMessageElement(name, message) {
    const messageItem = document.createElement('div');
    messageItem.className = 'message-item';
    
    const now = new Date();
    const dateString = now.toISOString().split('T')[0];
    
    messageItem.innerHTML = `
        <div class="message-header">
            <span class="message-author">${name}</span>
            <span class="message-date">${dateString}</span>
        </div>
        <p class="message-content">${message}</p>
    `;
    
    return messageItem;
}

// 处理联系表单提交
function handleContactSubmit(e) {
    e.preventDefault();
    
    const name = document.getElementById('contact-name').value;
    const email = document.getElementById('contact-email').value;
    const subject = document.getElementById('contact-subject').value;
    const message = document.getElementById('contact-message').value;
    
    if (!name || !email || !message) {
        showNotification('请填写必填字段', 'error');
        return;
    }

    // 模拟发送邮件（实际项目中需要后端支持）
    const mailtoLink = `mailto:wangbo@example.com?subject=${encodeURIComponent(subject || '来自个人主页的联系')}&body=${encodeURIComponent(`姓名: ${name}\n邮箱: ${email}\n\n${message}`)}`;
    
    // 打开默认邮件客户端
    window.location.href = mailtoLink;
    
    // 清空表单
    contactForm.reset();
    
    showNotification('联系信息已准备发送！', 'success');
}

// 显示通知
function showNotification(message, type) {
    // 创建通知元素
    const notification = document.createElement('div');
    notification.className = `notification ${type}`;
    notification.textContent = message;
    
    // 添加样式
    notification.style.cssText = `
        position: fixed;
        top: 100px;
        right: 20px;
        padding: 15px 20px;
        border-radius: 5px;
        color: white;
        font-weight: 500;
        z-index: 10000;
        transform: translateX(400px);
        transition: transform 0.3s ease;
        max-width: 300px;
    `;
    
    if (type === 'success') {
        notification.style.background = '#10b981';
    } else if (type === 'error') {
        notification.style.background = '#ef4444';
    } else {
        notification.style.background = '#3b82f6';
    }
    
    document.body.appendChild(notification);
    
    // 显示动画
    setTimeout(() => {
        notification.style.transform = 'translateX(0)';
    }, 100);
    
    // 3秒后自动移除
    setTimeout(() => {
        notification.style.transform = 'translateX(400px)';
        setTimeout(() => {
            if (notification.parentNode) {
                notification.parentNode.removeChild(notification);
            }
        }, 300);
    }, 3000);
}

// 滚动效果
function initScrollEffects() {
    // 淡入动画
    const fadeElements = document.querySelectorAll('.about-content, .skills-grid, .portfolio-grid, .guestbook-content, .contact-content');
    
    const fadeObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
            }
        });
    }, { threshold: 0.1 });
    
    fadeElements.forEach(element => {
        element.style.opacity = '0';
        element.style.transform = 'translateY(30px)';
        element.style.transition = 'opacity 0.6s ease, transform 0.6s ease';
        fadeObserver.observe(element);
    });
}

// 平滑滚动
function initSmoothScrolling() {
    const navLinks = document.querySelectorAll('a[href^="#"]');
    
    navLinks.forEach(link => {
        link.addEventListener('click', function(e) {
            e.preventDefault();
            
            const targetId = this.getAttribute('href');
            const targetElement = document.querySelector(targetId);
            
            if (targetElement) {
                const offsetTop = targetElement.offsetTop - 70; // 考虑导航栏高度
                
                window.scrollTo({
                    top: offsetTop,
                    behavior: 'smooth'
                });
            }
        });
    });
}

